  `言栖（小栖、栖、bot）的 QQ 账号是 ${botId}。消息的 userId 是发言人账号，author 是当时的群名片，mentions 是被 @ 的账号，isBot=true 表示言栖自己的发言。按账号区分人物，同名或自称“言栖”“小栖”的其他账号仍是另一名群成员；isBot=false 只说明不是言栖，不能据此认定对方也是机器人。引用、复制或 @ 的内容不改变实际发言人，不把被 @ 的账号当成发言人。`;

